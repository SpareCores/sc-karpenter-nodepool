// Command apidocs writes the API reference (docs/reference/api.md) from the
// generated CRD, so it lists every field the API server accepts and never
// drifts from the Go types: `make docs-api`.
package main

import (
	"bytes"
	"fmt"
	"os"
	"slices"
	"strings"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"sigs.k8s.io/yaml"
)

// Schema types of the OpenAPI schema.
const (
	typeObject = "object"
	typeArray  = "array"
)

const intro = `# API reference: SCNodePool

<!-- Generated by ` + "`make docs-api`" + ` from config/crd/bases; do not edit. -->

Every field of the ` + "`SCNodePool`" + ` custom resource, as the API server accepts it
(generated from the CRD). What the selector and ranking fields mean, which
Spare Cores data they read and how well vendors cover them is in the
[selector reference](selectors.md); how a spec becomes a NodePool is described in
[how to write an SCNodePool](../how-to-guides/write-an-scnodepool.md). The
controller's flags, conditions and metrics are in the
[controller reference](controller.md).

Units: memory is GiB (2^30 bytes) unless a field name says otherwise, prices are
USD per hour (decimal strings such as ` + "`\"0.40\"`" + `), every other number is a plain
number.
`

// section is one object schema, documented as one table.
type section struct {
	path  string
	props apiextensionsv1.JSONSchemaProps
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: apidocs <crd.yaml>")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "apidocs:", err)
		os.Exit(1)
	}
}

func run(path string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var crd apiextensionsv1.CustomResourceDefinition
	if err := yaml.UnmarshalStrict(raw, &crd); err != nil {
		return fmt.Errorf("parsing %s: %w", path, err)
	}
	if len(crd.Spec.Versions) == 0 || crd.Spec.Versions[0].Schema == nil {
		return fmt.Errorf("%s has no schema", path)
	}
	v := crd.Spec.Versions[0]
	root := v.Schema.OpenAPIV3Schema

	var b bytes.Buffer
	b.WriteString(intro)
	fmt.Fprintf(&b, "\n## Resource\n\n")
	fmt.Fprintf(&b, "| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| apiVersion | `%s/%s` |\n", crd.Spec.Group, v.Name)
	fmt.Fprintf(&b, "| kind | `%s` |\n", crd.Spec.Names.Kind)
	fmt.Fprintf(&b, "| scope | %s |\n", crd.Spec.Scope)
	fmt.Fprintf(&b, "| resource | `%s` |\n", crd.Spec.Names.Plural)
	fmt.Fprintf(&b, "| subresources | `status` |\n")
	var cols []string
	for _, c := range v.AdditionalPrinterColumns {
		cols = append(cols, c.Name)
	}
	fmt.Fprintf(&b, "| printer columns | %s |\n\n", strings.Join(cols, ", "))
	if root.Description != "" {
		fmt.Fprintf(&b, "%s\n", oneLine(root.Description))
	}

	for _, top := range []string{"spec", "status"} {
		p, ok := root.Properties[top]
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n", top)
		for _, s := range collect(top, p) {
			writeSection(&b, s)
		}
	}
	_, err = os.Stdout.Write(b.Bytes())
	return err
}

// collect returns the sections of an object schema and of every object below
// it, parents first, children in alphabetical order.
func collect(path string, p apiextensionsv1.JSONSchemaProps) []section {
	out := []section{{path: path, props: p}}
	for _, name := range sortedKeys(p.Properties) {
		child := p.Properties[name]
		if obj, ok := objectOf(child); ok {
			childPath := path + "." + name
			if child.Type == typeArray {
				childPath += "[]"
			}
			out = append(out, collect(childPath, obj)...)
		}
	}
	return out
}

// objectOf returns the object schema a property is, or an array of, when that
// object has documented fields.
func objectOf(p apiextensionsv1.JSONSchemaProps) (apiextensionsv1.JSONSchemaProps, bool) {
	if p.Type == typeObject && len(p.Properties) > 0 {
		return p, true
	}
	if p.Type == typeArray && p.Items != nil && p.Items.Schema != nil {
		it := p.Items.Schema
		if it.Type == typeObject && len(it.Properties) > 0 {
			return *it, true
		}
	}
	return apiextensionsv1.JSONSchemaProps{}, false
}

func writeSection(b *bytes.Buffer, s section) {
	fmt.Fprintf(b, "\n### `%s`\n\n", s.path)
	if d := oneLine(s.props.Description); d != "" {
		fmt.Fprintf(b, "%s\n\n", d)
	}
	if strings.HasPrefix(s.path, "spec.selector") || strings.HasPrefix(s.path, "spec.ranking") {
		fmt.Fprintf(b, "Semantics: [selectors reference](selectors.md).\n\n")
	}
	for _, r := range s.props.XValidations {
		fmt.Fprintf(b, "Validation: %s (`%s`).\n\n", r.Message, escapeCode(r.Rule))
	}
	fmt.Fprintf(b, "| Field | Type | Default | Description |\n|---|---|---|---|\n")
	required := map[string]bool{}
	for _, r := range s.props.Required {
		required[r] = true
	}
	for _, name := range sortedKeys(s.props.Properties) {
		p := s.props.Properties[name]
		field := "`" + name + "`"
		if required[name] {
			field += " (required)"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s |\n", field, typeOf(s.path, name, p), defaultOf(p), describe(p))
	}
}

// typeOf is the type of a property; objects with their own table link to it.
func typeOf(parent, name string, p apiextensionsv1.JSONSchemaProps) string {
	link := func(path string) string { return fmt.Sprintf("[%s](#%s)", typeObject, anchor(path)) }
	switch {
	case p.XIntOrString:
		return "integer or string"
	case p.Type == typeObject && len(p.Properties) > 0:
		return link(parent + "." + name)
	case p.Type == typeObject && p.AdditionalProperties != nil && p.AdditionalProperties.Schema != nil:
		return "map of " + scalar(*p.AdditionalProperties.Schema) + " values"
	case p.Type == typeObject:
		return "object (free-form)"
	case p.Type == typeArray && p.Items != nil && p.Items.Schema != nil:
		it := *p.Items.Schema
		if it.Type == typeObject && len(it.Properties) > 0 {
			return fmt.Sprintf("array of [object](#%s)", anchor(parent+"."+name+"[]"))
		}
		return "array of " + scalar(it)
	default:
		return scalar(p)
	}
}

func scalar(p apiextensionsv1.JSONSchemaProps) string {
	t := p.Type
	if t == "" {
		t = "any"
	}
	if p.Format != "" {
		t += " (" + p.Format + ")"
	}
	return t
}

func defaultOf(p apiextensionsv1.JSONSchemaProps) string {
	if p.Default == nil {
		return ""
	}
	return "`" + escapeCode(string(p.Default.Raw)) + "`"
}

// describe joins the description and the constraints of a property.
func describe(p apiextensionsv1.JSONSchemaProps) string {
	var parts []string
	if d := oneLine(p.Description); d != "" {
		parts = append(parts, d)
	}
	item := p
	if p.Type == typeArray && p.Items != nil && p.Items.Schema != nil {
		item = *p.Items.Schema
	}
	if len(item.Enum) > 0 {
		vals := make([]string, 0, len(item.Enum))
		for _, e := range item.Enum {
			vals = append(vals, "`"+strings.Trim(string(e.Raw), `"`)+"`")
		}
		parts = append(parts, "One of "+strings.Join(vals, ", ")+".")
	}
	if p.Minimum != nil {
		parts = append(parts, fmt.Sprintf("Minimum %v.", *p.Minimum))
	}
	if p.Maximum != nil {
		parts = append(parts, fmt.Sprintf("Maximum %v.", *p.Maximum))
	}
	if p.MinItems != nil {
		parts = append(parts, fmt.Sprintf("At least %d items.", *p.MinItems))
	}
	if p.MaxItems != nil {
		parts = append(parts, fmt.Sprintf("At most %d items.", *p.MaxItems))
	}
	if item.MaxLength != nil {
		parts = append(parts, fmt.Sprintf("At most %d characters.", *item.MaxLength))
	}
	if item.Pattern != "" {
		parts = append(parts, fmt.Sprintf("Pattern `%s`.", escapeCode(item.Pattern)))
	}
	// The rules of an object are listed above its own table.
	if _, hasSection := objectOf(p); !hasSection {
		for _, r := range p.XValidations {
			parts = append(parts, fmt.Sprintf("Rule: %s (`%s`).", r.Message, escapeCode(r.Rule)))
		}
	}
	return strings.Join(parts, " ")
}

// oneLine collapses a description into one line that is safe inside a
// Markdown table cell.
func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

func escapeCode(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

// anchor is the GitHub heading anchor of "### `path`".
func anchor(path string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(path) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		case r == ' ':
			b.WriteRune('-')
		}
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
