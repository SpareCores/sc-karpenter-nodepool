// Package nodepool renders and validates the Karpenter NodePool generated
// from an SCNodePool (overview §3.4 steps 7–8, §3.6). It has no Kubernetes
// client: NodePools are handled as unstructured objects so that every
// provider's NodePool CRD version is accepted.
package nodepool

import (
	"errors"
	"slices"
	"time"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"k8s.io/apimachinery/pkg/runtime/schema"

	"github.com/SpareCores/sc-karpenter-nodepool/internal/providers"
)

// Labels, annotations and the field manager of generated NodePools.
const (
	// FieldManager is the server-side apply field manager.
	FieldManager = "sc-karpenter-nodepool"
	// LabelManagedBy marks NodePools generated by this controller.
	LabelManagedBy = "app.kubernetes.io/managed-by"
	// ManagedByValue is the value of LabelManagedBy.
	ManagedByValue = "sc-karpenter-nodepool"
	// LabelSCNodePool names the SCNodePool a NodePool was generated from.
	LabelSCNodePool = "karpenter.sparecores.com/scnodepool"
	// AnnotationDataTimestamp is the freshness of the Spare Cores data used.
	AnnotationDataTimestamp = "karpenter.sparecores.com/data-timestamp"
	// AnnotationSelectionHash identifies the emitted instance-type list.
	AnnotationSelectionHash = "karpenter.sparecores.com/selection-hash"

	// MaxRequirements is the NodePool CRD limit (overview §5.1.2).
	MaxRequirements = 100
	// DefaultConsolidateAfter is set when the template has none: the field
	// is required by the v1.14.1 NodePool CRD every current provider ships.
	DefaultConsolidateAfter = "0s"
)

// GVK is the Karpenter NodePool kind every provider uses.
var GVK = schema.GroupVersionKind{Group: "karpenter.sh", Version: "v1", Kind: "NodePool"}

// Errors of Render and Validate; test with errors.Is.
var (
	// ErrInvalidTemplate: nodePoolTemplate cannot be parsed or misses
	// required fields.
	ErrInvalidTemplate = errors.New("invalid nodePoolTemplate")
	// ErrEmptySelection: no instance type is left to emit.
	ErrEmptySelection = errors.New("no instance types to emit")
	// ErrForbiddenKey: the template uses a requirement key the provider's
	// rules forbid.
	ErrForbiddenKey = errors.New("forbidden requirement key")
	// ErrInvalidNodePool: the rendered NodePool fails validation.
	ErrInvalidNodePool = errors.New("invalid NodePool")
)

// New returns an empty NodePool object.
func New() *unstructured.Unstructured {
	u := &unstructured.Unstructured{}
	u.SetGroupVersionKind(GVK)
	return u
}

// IsOurs reports whether a NodePool is labelled as generated from the named
// SCNodePool.
func IsOurs(np *unstructured.Unstructured, scNodePool string) bool {
	if np == nil {
		return false
	}
	l := np.GetLabels()
	return l[LabelManagedBy] == ManagedByValue && l[LabelSCNodePool] == scNodePool
}

// RequirementsOf returns spec.template.spec.requirements of a NodePool.
func RequirementsOf(np *unstructured.Unstructured) []Requirement {
	if np == nil {
		return nil
	}
	raw, _, _ := unstructured.NestedSlice(np.Object, "spec", "template", "spec", "requirements")
	out := make([]Requirement, 0, len(raw))
	for _, item := range raw {
		if m, ok := item.(map[string]any); ok {
			out = append(out, requirementFromMap(m))
		}
	}
	return out
}

// InstanceTypes returns the sorted values of the NodePool's
// node.kubernetes.io/instance-type In requirement (nil without one). A
// generated NodePool has exactly one.
func InstanceTypes(np *unstructured.Unstructured) []string {
	for _, r := range RequirementsOf(np) {
		if r.Key == providers.LabelInstanceType && r.Operator == OpIn {
			return slices.Sorted(slices.Values(r.Values))
		}
	}
	return nil
}

// NodeClassRefOf returns spec.template.spec.nodeClassRef of a NodePool.
func NodeClassRefOf(np *unstructured.Unstructured) (NodeClassRef, bool) {
	if np == nil {
		return NodeClassRef{}, false
	}
	m, ok, _ := unstructured.NestedStringMap(np.Object, "spec", "template", "spec", "nodeClassRef")
	if !ok {
		return NodeClassRef{}, false
	}
	return NodeClassRef{Group: m["group"], Kind: m["kind"], Name: m["name"]}, true
}

// Condition is one status condition of a NodePool or NodeClaim.
type Condition struct {
	Type               string
	Status             metav1.ConditionStatus
	Reason             string
	Message            string
	LastTransitionTime time.Time
}

// Conditions returns status.conditions of an unstructured Karpenter object.
func Conditions(u *unstructured.Unstructured) []Condition {
	if u == nil {
		return nil
	}
	raw, _, _ := unstructured.NestedSlice(u.Object, "status", "conditions")
	out := make([]Condition, 0, len(raw))
	for _, item := range raw {
		m, ok := item.(map[string]any)
		if !ok {
			continue
		}
		c := Condition{
			Type:    str(m["type"]),
			Status:  metav1.ConditionStatus(str(m["status"])),
			Reason:  str(m["reason"]),
			Message: str(m["message"]),
		}
		if t, err := time.Parse(time.RFC3339, str(m["lastTransitionTime"])); err == nil {
			c.LastTransitionTime = t
		}
		out = append(out, c)
	}
	return out
}

// FindCondition returns the condition of the given type.
func FindCondition(conds []Condition, t string) (Condition, bool) {
	for _, c := range conds {
		if c.Type == t {
			return c, true
		}
	}
	return Condition{}, false
}

// LastAppliedTime is when this controller's field manager last changed the
// NodePool (from metadata.managedFields), falling back to its creation time.
func LastAppliedTime(np *unstructured.Unstructured) time.Time {
	var last time.Time
	for _, mf := range np.GetManagedFields() {
		if mf.Manager == FieldManager && mf.Operation == metav1.ManagedFieldsOperationApply && mf.Time != nil &&
			mf.Time.After(last) {
			last = mf.Time.Time
		}
	}
	if last.IsZero() {
		return np.GetCreationTimestamp().Time
	}
	return last
}

func str(v any) string {
	s, _ := v.(string)
	return s
}
